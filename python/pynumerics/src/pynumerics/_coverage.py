"""The map from every public Numerics type to its pynumerics wrapper, checked by ``tests/test_coverage.py``.

:data:`COVERAGE` has one entry per public type of ``Numerics.dll`` (``Assembly.GetExportedTypes``),
keyed by the .NET full name (nested types with ``+``, generic types with their arity):

``Wrapped(target, members, rest)``
    ``target`` is the dotted path of the pynumerics object that wraps the type (a class, function,
    module or enum). For a class or struct, ``members`` maps each public member the type declares
    (see :func:`net_members`) to the attribute of ``target`` that wraps it, or to a ``Todo`` or
    ``Excluded``; ``rest`` covers the declared members not listed, and None means every member
    must be listed.
``Excluded(reason)``
    Deliberately not wrapped, with the reason.
``Todo(module)``
    Not wrapped yet; ``module`` names the pynumerics module that will hold the wrapper, one of
    :data:`MODULES`.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Mapping
from dataclasses import dataclass, field
from typing import Any, Union


@dataclass(frozen=True)
class Todo:
    """A type or member not wrapped yet.

    Parameters
    ----------
    module : str
        The pynumerics module that will hold the wrapper, one of :data:`MODULES`.
    """

    module: str


@dataclass(frozen=True)
class Excluded:
    """A type or member deliberately not wrapped.

    Parameters
    ----------
    reason : str
        Why it has no wrapper.
    """

    reason: str


@dataclass(frozen=True)
class Wrapped:
    """A type wrapped by a pynumerics object.

    Parameters
    ----------
    target : str
        The dotted path of the wrapping object, for example ``"pynumerics.distributions.Normal"``.
    members : Mapping
        Declared .NET member name (``".ctor"`` for the constructors) to the attribute of ``target``
        that wraps it, a dotted ``pynumerics.`` path, a :class:`Todo` or an :class:`Excluded`.
    rest : Todo or Excluded or None
        The state of the declared members not in ``members``; None requires every one listed.
    """

    target: str
    members: Mapping[str, Union[str, Todo, Excluded]] = field(default_factory=dict)
    rest: Union[Todo, Excluded, None] = None


Entry = Union[Wrapped, Excluded, Todo]

MODULES = frozenset({
    "bootstrap", "copulas", "data", "differentiation", "distributions", "download", "functions",
    "goodness_of_fit", "graphs", "hypothesis_tests", "integration", "linalg", "machine_learning",
    "mathematics", "mcmc", "multivariate", "ode", "optimization", "probability", "regional", "roots", "sampling",
    "special", "statistics", "timeseries",
})
"""The pynumerics modules a :class:`Todo` may name."""

_OBJECT_MEMBERS = frozenset({"ToString", "Equals", "GetHashCode", "GetType", "Finalize", "MemberwiseClone",
                             "Deconstruct", "<Clone>$", "PrintMembers", "EqualityContract"})


def net_members(clr_type: Any) -> list[str]:
    """Return the public members a .NET type declares, as the coverage map names them.

    Methods (overloads count once), properties, fields and events declared on the type itself,
    plus ``".ctor"`` when it has a public constructor that takes arguments or the type has
    instance members. Accessors, operators, ``object`` overrides and overrides of a base member
    (covered by the base type's entry) are left out.

    Parameters
    ----------
    clr_type : System.Type
        The .NET type.

    Returns
    -------
    list of str
        The member names, sorted.
    """
    import System  # noqa: PLC0415 - the caller started the runtime

    flags = System.Reflection.BindingFlags
    declared = flags.Public | flags.Instance | flags.Static | flags.DeclaredOnly
    instance = flags.Public | flags.Instance | flags.DeclaredOnly
    names: set[str] = set()
    constructors = list(clr_type.GetConstructors())
    has_instance = (any(not m.IsSpecialName for m in clr_type.GetMethods(instance))
                    or len(clr_type.GetProperties(instance)) > 0)
    if constructors and (has_instance or any(len(c.GetParameters()) for c in constructors)):
        names.add(".ctor")
    for method in clr_type.GetMethods(declared):
        if method.IsSpecialName or str(method.Name) in _OBJECT_MEMBERS:
            continue
        if method.IsVirtual and method.GetBaseDefinition().DeclaringType != method.DeclaringType:
            continue
        names.add(str(method.Name))
    for prop in clr_type.GetProperties(declared):
        accessor = prop.GetGetMethod() or prop.GetSetMethod()
        if accessor is not None and accessor.IsVirtual and accessor.GetBaseDefinition().DeclaringType != clr_type:
            continue
        if str(prop.Name) not in _OBJECT_MEMBERS:
            names.add(str(prop.Name))
    for item in clr_type.GetFields(declared):
        if not item.IsSpecialName:
            names.add(str(item.Name))
    for event in clr_type.GetEvents(declared):
        names.add(str(event.Name))
    return sorted(names)


def todo_counts() -> Counter:
    """Return the number of types marked :class:`Todo`, per pynumerics module.

    Returns
    -------
    collections.Counter
        Module name to the count of ``Todo`` type entries (member-level gaps are counted by the test).
    """
    return Counter(entry.module for entry in COVERAGE.values() if isinstance(entry, Todo))


