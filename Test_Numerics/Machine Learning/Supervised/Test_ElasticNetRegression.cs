        /// <summary>
        /// A constant predictor is excluded and leaves the other coefficients unchanged; duplicated predictors share
        /// the coefficient equally when α &lt; 1.
        /// </summary>
        [TestMethod]
        public void Test_ConstantAndCollinearColumns()
        {
            var (X, y) = Data();
            var Xc = new double[67, 9];
            var Xd = new double[67, 9];
            for (int i = 0; i < 67; i++)
            {
                for (int j = 0; j < 8; j++) { Xc[i, j] = X[i, j]; Xd[i, j] = X[i, j]; }
                Xc[i, 8] = 3.5;
                Xd[i, 8] = X[i, 0];
            }
            var reference = Fit(0.5);
            var constant = new ElasticNetRegression(Xc, y) { Alpha = 0.5, Tolerance = 1E-24 };
            constant.Fit();
            Assert.HasCount(reference.Lambdas.Length, constant.Lambdas);
            for (int k = 0; k < reference.Lambdas.Length; k++)
            {
                Assert.AreEqual(0.0, constant.Coefficients[k, 8]);
                for (int j = 0; j < 8; j++) Assert.AreEqual(reference.Coefficients[k, j], constant.Coefficients[k, j], 1E-12);
            }

            var duplicate = new ElasticNetRegression(Xd, y) { Alpha = 0.5, Tolerance = 1E-24 };
            duplicate.Fit();
            int last = duplicate.Lambdas.Length - 1;
            Assert.AreEqual(duplicate.Coefficients[last, 0], duplicate.Coefficients[last, 8], 1E-8);
        }

        /// <summary>
        /// On a larger problem that uses the parallel blocked cross products and batched column caching, every point
        /// satisfies the elastic net optimality (KKT) conditions, and refitting gives identical results.
        /// </summary>
        [TestMethod]
        public void Test_Large_KKT_And_Reproducible()
        {
            int n = 6000, p = 40;
            var rng = new Random(11);
            var X = new double[n, p];
            var y = new double[n];
            for (int i = 0; i < n; i++)
            {
                double prev = 0;
                for (int j = 0; j < p; j++)
                {
                    prev = 0.5 * prev + rng.NextDouble() - 0.5;
                    X[i, j] = 100.0 + 10.0 * j + prev;
                }
                y[i] = 2.0 + 3.0 * X[i, 2] - 2.0 * X[i, 7] + X[i, 30] + (rng.NextDouble() - 0.5);
            }
            var model = new ElasticNetRegression(X, y) { Alpha = 0.7, Tolerance = 1E-20 };
            model.Fit();
            var again = new ElasticNetRegression(X, y) { Alpha = 0.7, Tolerance = 1E-20 };
            again.Fit();
            CollectionAssert.AreEqual(model.Lambdas, again.Lambdas);
            for (int k = 0; k < model.Lambdas.Length; k++)
                for (int j = 0; j < p; j++) Assert.AreEqual(model.Coefficients[k, j], again.Coefficients[k, j], 0.0);

            // KKT on the standardized problem: with z the standardized predictors and r the residual,
            // |<z_j, r>/n| <= λα·sd(y)... evaluated on the original scale as |<x_j - mean_j, r>/n| / sd_j.
            var mean = new double[p];
            var sd = new double[p];
            for (int j = 0; j < p; j++)
            {
                double s = 0, ss = 0;
                for (int i = 0; i < n; i++) s += X[i, j];
                mean[j] = s / n;
                for (int i = 0; i < n; i++) ss += (X[i, j] - mean[j]) * (X[i, j] - mean[j]);
                sd[j] = Math.Sqrt(ss / n);
            }
            foreach (int k in new[] { 5, 20, model.Lambdas.Length - 1 })
            {
                double lambda = model.Lambdas[k];
                var r = new double[n];
                for (int i = 0; i < n; i++)
                {
                    double f = model.Intercepts[k];
                    for (int j = 0; j < p; j++) f += model.Coefficients[k, j] * X[i, j];
                    r[i] = y[i] - f;
                }
                for (int j = 0; j < p; j++)
                {
                    double g = 0;
                    for (int i = 0; i < n; i++) g += (X[i, j] - mean[j]) * r[i];
                    g = g / n / sd[j];
                    // Gradient of the penalty for standardized coefficient b_j = β_j·sd_j, scaled by sd(y) as in glmnet.
                    double b = model.Coefficients[k, j] * sd[j];
                    double ridge = lambda * (1 - 0.7) * b / YScale(y);
                    if (b == 0)
                        Assert.IsLessThanOrEqualTo(lambda * 0.7 * (1 + 1E-6), Math.Abs(g), $"inactive {j} at {k}");
                    else
                        Assert.AreEqual(lambda * 0.7 * Math.Sign(b), g - ridge, 1E-6 * lambda, $"active {j} at {k}");
                }
            }
        }

        /// <summary>
        /// Population standard deviation of the response.
        /// </summary>
        private static double YScale(double[] y)
        {
            double m = y.Average();
            return Math.Sqrt(y.Select(v => (v - m) * (v - m)).Sum() / y.Length);
        }

        /// <summary>
