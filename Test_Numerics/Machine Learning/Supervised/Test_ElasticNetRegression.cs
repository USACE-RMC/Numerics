        /// <summary>
        /// Cross-validation with fixed folds matches glmnet refits at the full-data penalties, and λ_min and λ_1se
        /// match cv.glmnet.
        /// </summary>
        /// <remarks>
        /// cv.glmnet fits each fold on its own penalty sequence and interpolates predictions to the full-data
        /// sequence; the exact reference refits each fold at the full-data penalties, which is what ElasticNetRegression
        /// does. On this data both give the same λ_min and λ_1se.
        /// </remarks>
        [TestMethod]
        public void Test_CrossValidation_FixedFolds()
        {
            var model = Fit(0.5);
            model.CrossValidate(FoldIds);
            var index = new int[] { 0, 10, 18, 19, 30, 53, 72 };
            var cvm = new double[] { 1.4260937282259702, 0.8587647501540535, 0.6720557502443547, 0.6624791056675896, 0.6249481056397496, 0.5871630491465841, 0.5890883168425736 };
            var cvsd = new double[] { 0.1465603344183819, 0.11276947128987146, 0.09651278595667637, 0.09719558296470607, 0.10640737182477636, 0.08810300401926514, 0.08098154666946848 };
            for (int i = 0; i < index.Length; i++)
            {
                Assert.AreEqual(cvm[i], model.CrossValidationError[index[i]], 1E-11 * cvm[i]);
                Assert.AreEqual(cvsd[i], model.CrossValidationStandardError[index[i]], 1E-9 * cvsd[i]);
            }
            Assert.AreEqual(53, model.LambdaMinIndex);
            Assert.AreEqual(18, model.LambdaOneStandardErrorIndex);
            Assert.AreEqual(53, model.LambdaMinIndex);
            Assert.AreEqual(18, model.LambdaOneStandardErrorIndex);
            Assert.AreEqual(model.Lambdas[model.LambdaMinIndex], model.LambdaMin);
            Assert.IsGreaterThan(model.LambdaMin, model.LambdaOneStandardError);
        }

        /// <summary>
        /// Seeded fold assignment is reproducible and balanced; the cross-validated error is the same as with the
        /// equivalent explicit fold labels.
        /// </summary>
        [TestMethod]
        public void Test_CrossValidation_Seeded()
        {
            var a = Fit(1.0);
            a.CrossValidate(10, 42);
            var b = Fit(1.0);
            b.CrossValidate(10, 42);
            CollectionAssert.AreEqual(a.FoldIds, b.FoldIds);
            CollectionAssert.AreEqual(a.CrossValidationError, b.CrossValidationError);
            var counts = a.FoldIds.GroupBy(f => f).Select(g => g.Count()).ToArray();
            Assert.HasCount(10, counts);
            Assert.IsLessThanOrEqualTo(1, counts.Max() - counts.Min());
            var c = Fit(1.0);
            c.CrossValidate(a.FoldIds);
            CollectionAssert.AreEqual(a.CrossValidationError, c.CrossValidationError);
            var d = Fit(1.0);
            d.CrossValidate(10, 43);
            CollectionAssert.AreNotEqual(a.FoldIds, d.FoldIds);
        }

        /// <summary>
        /// λ_min and λ_1se require cross-validation of the current path: they throw before cross-validation and
        /// after a refit, and the refit clears the previous cross-validation results.
        /// </summary>
        [TestMethod]
        public void Test_CrossValidation_ClearedByRefit()
        {
            var model = Fit(1.0);
            Assert.ThrowsExactly<InvalidOperationException>(() => _ = model.LambdaMin);
            Assert.ThrowsExactly<InvalidOperationException>(() => _ = model.LambdaOneStandardError);

            model.CrossValidate(FoldIds);
            Assert.IsTrue(model.IsCrossValidated);
            Assert.AreEqual(model.Lambdas[model.LambdaMinIndex], model.LambdaMin);

            model.Alpha = 0.1;
            model.NumberOfLambdas = 10;
            model.Fit();
            Assert.IsFalse(model.IsCrossValidated);
            Assert.AreEqual(-1, model.LambdaMinIndex);
            Assert.AreEqual(-1, model.LambdaOneStandardErrorIndex);
            Assert.IsNull(model.CrossValidationError);
            Assert.IsNull(model.CrossValidationStandardError);
            Assert.IsNull(model.FoldIds);
            Assert.ThrowsExactly<InvalidOperationException>(() => _ = model.LambdaMin);
            Assert.ThrowsExactly<InvalidOperationException>(() => _ = model.LambdaOneStandardError);

            model.CrossValidate(FoldIds);
            Assert.HasCount(model.Lambdas.Length, model.CrossValidationError);
            Assert.AreEqual(model.Lambdas[model.LambdaMinIndex], model.LambdaMin);
        }

