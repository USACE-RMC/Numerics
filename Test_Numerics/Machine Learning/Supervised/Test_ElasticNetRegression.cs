        private static ElasticNetRegression Fit(double alpha, int rows = 67, Action<ElasticNetRegression> configure = null!)
        {
            var (X, y) = Data(rows);
            var model = new ElasticNetRegression(X, y) { Alpha = alpha, Tolerance = 1E-24 };
            configure?.Invoke(model);
            model.Fit();
            return model;
        }

        /// <summary>
        /// Compares a fitted path with the reference.
        /// </summary>
        private static void AssertPath(PathReference expected, ElasticNetRegression model)
        {
            Assert.IsTrue(model.Converged);
            Assert.HasCount(expected.Length, model.Lambdas);
            for (int i = 0; i < expected.Index.Length; i++)
            {
                int k = expected.Index[i];
                Assert.AreEqual(expected.Lambda[i], model.Lambdas[k], 1E-12 * expected.Lambda[i]);
                Assert.AreEqual(expected.Intercept[i], model.Intercepts[k], 1E-10);
                Assert.AreEqual(expected.DevianceRatio[i], model.DevianceRatio[k], 1E-12);
                for (int j = 0; j < 8; j++)
                    Assert.AreEqual(expected.Beta[i, j], model.Coefficients[k, j], 1E-10);
            }
        }

