            Assert.ThrowsExactly<ArgumentException>(() => new ElasticNetRegression(X, y) { PenaltyFactors = new double[8] }.Fit());
            Assert.ThrowsExactly<ArgumentException>(() => new ElasticNetRegression(X, y) { PenaltyFactors = new double[3] }.Fit());
