        /// <summary>
        /// With a nugget, kriging honors the data at an observed location with zero variance, and the variogram
        /// functions follow the gstat conventions.
        /// </summary>
        [TestMethod]
        public void Test_ExactAtData_AndVariogram()
        {
            var kriging = new Kriging(Coordinates(MeuseX, MeuseY), LogZinc, VariogramModel.Spherical, 0.05, 0.6, 900);
            var (mean, variance) = kriging.PredictWithVariance(new[] { MeuseX[3], MeuseY[3] });
            Assert.AreEqual(LogZinc[3], mean, 1E-10);
            Assert.AreEqual(0d, variance, 1E-10);
            Assert.AreEqual(0.65, kriging.Sill, 1E-15);
            Assert.AreEqual(0d, kriging.Semivariance(0d));
            Assert.AreEqual(0.05 + 0.6 * (1.5 * 0.5 - 0.5 * 0.125), kriging.Semivariance(450), 1E-15);
            Assert.AreEqual(0.65, kriging.Semivariance(2000), 1E-15);
            Assert.AreEqual(0.65, kriging.Covariance(0d), 1E-15);
            var gaussian = new Kriging(Coordinates(MeuseX, MeuseY), LogZinc, VariogramModel.Gaussian, 0.05, 0.6, 500);
            Assert.AreEqual(0.6 * Math.Exp(-1), gaussian.Covariance(500), 1E-15);
        }

        /// <summary>
        /// A custom distance that equals the Euclidean distance gives the same predictions, and simple kriging adds
        /// the known mean back.
        /// </summary>
        [TestMethod]
        public void Test_CustomDistance_AndSimpleMean()
        {
            var coordinates = Coordinates(MeuseX, MeuseY);
            Func<double[], double[], double> euclidean = (a, b) => Math.Sqrt((a[0] - b[0]) * (a[0] - b[0]) + (a[1] - b[1]) * (a[1] - b[1]));
            var reference = new Kriging(coordinates, LogZinc, VariogramModel.Exponential, 0.05, 0.6, 300);
            var custom = new Kriging(coordinates, LogZinc, VariogramModel.Exponential, 0.05, 0.6, 300, euclidean);
            var grid = Coordinates(GridX, GridY);
            var (m1, v1) = reference.PredictWithVariance(grid);
            var (m2, v2) = custom.PredictWithVariance(grid);
            AssertRelative(m1, m2, 1E-12, "mean");
            AssertRelative(v1, v2, 1E-12, "variance");

            var far = new double[] { 0, 0 };
            var simple = new Kriging(coordinates, LogZinc, VariogramModel.Exponential, 0.05, 0.6, 300, KrigingType.Simple, 5.9);
            var (mean, variance) = simple.PredictWithVariance(far);
            Assert.AreEqual(5.9, mean, 1E-10);
            Assert.AreEqual(0.65, variance, 1E-10);
            Assert.AreEqual(5.9, simple.KnownMean);
        }

        /// <summary>
        /// Invalid arguments throw.
        /// </summary>
        [TestMethod]
        public void Test_InvalidArguments()
        {
            var c = Coordinates(GridX, GridY);
            var v = new double[GridX.Length];
            Assert.ThrowsExactly<ArgumentNullException>(() => new Kriging(null!, v, VariogramModel.Spherical, 0, 1, 1));
            Assert.ThrowsExactly<ArgumentNullException>(() => new Kriging(c, null!, VariogramModel.Spherical, 0, 1, 1));
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => new Kriging(c, v, VariogramModel.Spherical, -1, 1, 1));
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => new Kriging(c, v, VariogramModel.Spherical, 0, 0, 1));
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => new Kriging(c, v, VariogramModel.Spherical, 0, 1, 0));
            Assert.ThrowsExactly<ArgumentException>(() => new Kriging(c, new double[3], VariogramModel.Spherical, 0, 1, 1));
            Assert.ThrowsExactly<ArgumentException>(() => new Kriging(c, v, VariogramModel.Spherical, 0, 1, 1, (a, b) => 0, KrigingType.Universal));
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => new Kriging(c, v, (VariogramModel)7, 0, 1, 1));
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => new Kriging(c, v, VariogramModel.Spherical, 0, 1, 1, (KrigingType)7));
            var kriging = new Kriging(c, v, VariogramModel.Spherical, 0, 1, 1000);
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => kriging.Semivariance(-1));
            Assert.ThrowsExactly<ArgumentException>(() => kriging.PredictWithVariance(new double[] { 1, 2, 3 }));
        }

