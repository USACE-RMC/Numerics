        /// <summary>
        /// Returns the coordinate pairs as a two-column array.
        /// </summary>
        private static double[,] Coordinates(double[] x, double[] y)
        {
            var result = new double[x.Length, 2];
            for (int i = 0; i < x.Length; i++)
            {
                result[i, 0] = x[i];
                result[i, 1] = y[i];
            }
            return result;
        }

        /// <summary>
        /// Asserts relative agreement of the first expected.Length entries.
        /// </summary>
        private static void AssertRelative(double[] expected, double[] actual, double tolerance, string label)
        {
            for (int i = 0; i < expected.Length; i++)
                Assert.AreEqual(expected[i], actual[i], tolerance * Math.Abs(expected[i]), $"{label}[{i}]");
        }

