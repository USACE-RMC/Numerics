        /// <summary>
        /// The ordinary kriging example of Isaaks and Srivastava (1989), chapter 12: seven samples, covariance
        /// C(h) = 10 exp(-0.3 h), estimate at (65, 137). The book reports the estimate 592.7, weights 0.173, 0.318,
        /// 0.129, 0.086, 0.151, 0.057, 0.086, and the kriging variance 8.96. gstat::krige gives the values to full
        /// precision.
        /// </summary>
        [TestMethod]
        public void Test_IsaaksSrivastava_OrdinaryKriging()
        {
            var locations = new double[,] { { 61, 139 }, { 63, 140 }, { 64, 129 }, { 68, 128 }, { 71, 140 }, { 73, 141 }, { 75, 128 } };
            var values = new double[] { 477, 696, 227, 646, 606, 791, 783 };
            var kriging = new Kriging(locations, values, VariogramModel.Exponential, 0.0, 10.0, 1.0 / 0.3);
            var (mean, variance) = kriging.PredictWithVariance(new double[] { 65, 137 });
            Assert.AreEqual(592.728942789743, mean, 1E-10 * mean);
            Assert.AreEqual(8.95605278865636, variance, 1E-10 * variance);
            Assert.AreEqual(592.7, mean, 0.05);
            Assert.AreEqual(8.96, variance, 0.005);
            // The prediction is linear in the data, so the kriging weights are the predictions for unit vectors.
            var weights = new[] { 0.173, 0.318, 0.129, 0.086, 0.151, 0.057, 0.086 };
            for (int i = 0; i < values.Length; i++)
            {
                var unit = new double[values.Length];
                unit[i] = 1d;
                var single = new Kriging(locations, unit, VariogramModel.Exponential, 0.0, 10.0, 1.0 / 0.3);
                Assert.AreEqual(weights[i], single.PredictWithVariance(new double[] { 65, 137 }).Mean, 0.0005, $"weight {i}");
            }
        }

