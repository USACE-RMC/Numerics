        /// <summary>
        /// With Polish on, the best point after the planned budget is refined by Nelder-Mead; DDS stalls in
        /// curved valleys, so the polish reaches the Rosenbrock minimum it would not reach alone.
        /// </summary>
        [TestMethod]
        public void Test_Polish()
        {
            var lower = new[] { -5d, -5d, -5d };
            var upper = new[] { 5d, 5d, 5d };
            var plain = new DynamicallyDimensionedSearch(OptimizerFingerprint.Rosenbrock, 3, lower, upper) { ComputeHessian = false };
            plain.Minimize();
            var polished = new DynamicallyDimensionedSearch(OptimizerFingerprint.Rosenbrock, 3, lower, upper) { Polish = true };
            polished.Minimize();
            Assert.AreEqual(OptimizationStatus.Success, polished.Status);
            Assert.IsLessThan(plain.BestParameterSet.Fitness, polished.BestParameterSet.Fitness);
            Assert.IsLessThan(1E-8, polished.BestParameterSet.Fitness);
            Assert.IsGreaterThan(plain.FunctionEvaluations, polished.FunctionEvaluations);
            Assert.IsNotNull(polished.Hessian);
        }

        /// <summary>
        /// When fewer than 10 evaluations remain for the polish, too few for a local search, the polish is skipped:
        /// the run ends as the unpolished run does, with the same best point, status and Hessian, never with
        /// <see cref="OptimizationStatus.None"/>.
        /// </summary>
        [TestMethod]
        public void Test_PolishSkippedWhenBudgetNearlySpent()
        {
            var lower = new[] { -5d, -5d, -5d };
            var upper = new[] { 5d, 5d, 5d };
            var plain = new DynamicallyDimensionedSearch(OptimizerFingerprint.Rosenbrock, 3, lower, upper) { EvaluationBudget = 200, MaxFunctionEvaluations = 205 };
            plain.Minimize();
            foreach (bool reportFailure in new[] { true, false })
            {
                var polished = new DynamicallyDimensionedSearch(OptimizerFingerprint.Rosenbrock, 3, lower, upper) { EvaluationBudget = 200, MaxFunctionEvaluations = 205, Polish = true, ReportFailure = reportFailure };
                polished.Minimize();
                Assert.AreEqual(OptimizationStatus.Success, polished.Status);
                Assert.AreEqual(plain.FunctionEvaluations, polished.FunctionEvaluations);
                Assert.AreEqual(plain.BestParameterSet.Fitness, polished.BestParameterSet.Fitness, 0d);
                Assert.IsNotNull(polished.Hessian);
            }

            // With exactly 10 evaluations left the polish runs and stays within the cap.
            var ten = new DynamicallyDimensionedSearch(OptimizerFingerprint.Rosenbrock, 3, lower, upper) { EvaluationBudget = 200, MaxFunctionEvaluations = 210, Polish = true };
            ten.Minimize();
            Assert.AreNotEqual(OptimizationStatus.None, ten.Status);
            Assert.IsLessThanOrEqualTo(210, ten.FunctionEvaluations);
            Assert.IsLessThanOrEqualTo(plain.BestParameterSet.Fitness, ten.BestParameterSet.Fitness);
        }
