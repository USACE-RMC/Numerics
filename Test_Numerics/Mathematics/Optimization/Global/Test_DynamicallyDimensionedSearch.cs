        // Generated by generate-dds-oracles.py golden.
        // RosenbrockRandomStart: m=300, seed=12345, r=0.2, x0=None
        private static readonly double[] RosenbrockRandomStartX = { 1.0946599623913222, 1.211930379214572, 1.4667920000299661 };
        private const double RosenbrockRandomStartF = 0.07290042225273985;
        private static readonly double[] RosenbrockRandomStartTrace = { 23.0106635540253, 4.5328915242393535, 0.07290042225273985 };
        // CamelInitialPoint: m=200, seed=7, r=0.2, x0=[2.5, -1.5]
        private static readonly double[] CamelInitialPointX = { -0.08989866856241609, 0.740503291864123 };
        private const double CamelInitialPointF = -1.0250311586015715;
        private static readonly double[] CamelInitialPointTrace = { -0.7434012942578552, -0.8448091630111557, -1.0250311586015715 };
        // CornerWideSteps: m=100, seed=99, r=0.5, x0=None
        private static readonly double[] CornerWideStepsX = { 1.0, 1.0, 0.9729030312213184, 0.9689961841672494 };
        private const double CornerWideStepsF = 0.001695482313183962;
        private static readonly double[] CornerWideStepsTrace = { 0.38569799138618044, 0.009248759952445689, 0.001695482313183962 };

        /// <summary>
        /// Squared distance to the upper corner of the unit box, written with products only.
        /// </summary>
        private static double Corner(double[] x)
        {
            double s = 0;
            for (int i = 0; i < x.Length; i++) { double d = x[i] - 1d; s += d * d; }
            return s;
        }

        /// <summary>
        /// The Griewank function.
        /// </summary>
        private static double Griewank(double[] x)
        {
            double s = 0, p = 1;
            for (int i = 0; i < x.Length; i++) { s += x[i] * x[i]; p *= Math.Cos(x[i] / Math.Sqrt(i + 1)); }
            return s / 4000d - p + 1d;
        }

        /// <summary>
        /// The Rastrigin variant of Tolson and Shoemaker (2007, Table 1), with minimum -D on [-2, 2]^D.
        /// </summary>
        private static double PaperRastrigin(double[] x)
        {
            double s = 0;
            for (int i = 0; i < x.Length; i++) s += x[i] * x[i] - Math.Cos(2 * Math.PI * x[i]);
            return s;
        }

        private static double[] Fill(int n, double v) => Enumerable.Repeat(v, n).ToArray();

        private static void AssertGolden(DynamicallyDimensionedSearch solver, int m, double[] x, double f, double[] trace)
        {
            solver.Minimize();
            Assert.AreEqual(OptimizationStatus.Success, solver.Status);
            Assert.AreEqual(m, solver.FunctionEvaluations);
            Assert.AreEqual(f, solver.BestParameterSet.Fitness, 1E-12 * (1 + Math.Abs(f)));
            for (int j = 0; j < x.Length; j++)
                Assert.AreEqual(x[j], solver.BestParameterSet.Values[j], 1E-12);
            int[] at = { 10, m / 2, m };
            for (int k = 0; k < at.Length; k++)
                Assert.AreEqual(trace[k], solver.ParameterSetTrace[at[k] - 1].Fitness, 1E-12 * (1 + Math.Abs(trace[k])));
        }

        /// <summary>
        /// The random-start trajectory matches the paper transcription in the oracle script.
        /// </summary>
        [TestMethod]
        public void Test_MatchesOracle_RandomStart()
        {
            var solver = new DynamicallyDimensionedSearch(OptimizerFingerprint.Rosenbrock, 3, Fill(3, -2), Fill(3, 2)) { EvaluationBudget = 300, ComputeHessian = false };
            AssertGolden(solver, 300, RosenbrockRandomStartX, RosenbrockRandomStartF, RosenbrockRandomStartTrace);
        }

        /// <summary>
        /// The trajectory from a supplied initial point matches the oracle.
        /// </summary>
        [TestMethod]
        public void Test_MatchesOracle_InitialPoint()
        {
            var solver = new DynamicallyDimensionedSearch(OptimizerFingerprint.SixHumpCamel, 2, new[] { 2.5, -1.5 }, new[] { -3d, -2d }, new[] { 3d, 2d }) { EvaluationBudget = 200, PRNGSeed = 7, ComputeHessian = false };
            AssertGolden(solver, 200, CamelInitialPointX, CamelInitialPointF, CamelInitialPointTrace);
            Assert.AreEqual(199, solver.Iterations);
        }

        /// <summary>
        /// A wide perturbation toward a corner optimum exercises both branches of the reflection rule and matches the oracle.
        /// </summary>
        [TestMethod]
        public void Test_MatchesOracle_Reflection()
        {
            var solver = new DynamicallyDimensionedSearch(Corner, 4, Fill(4, 0), Fill(4, 1)) { EvaluationBudget = 100, PRNGSeed = 99, PerturbationSize = 0.5, ComputeHessian = false };
            AssertGolden(solver, 100, CornerWideStepsX, CornerWideStepsF, CornerWideStepsTrace);
        }

        /// <summary>
        /// Pins the seeded trajectory bit for bit with <see cref="OptimizerFingerprint"/>. A different
        /// fingerprint means different results.
        /// </summary>
        [TestMethod]
        public void Test_SeededRunFingerprint()
        {
            var a = new DynamicallyDimensionedSearch(OptimizerFingerprint.Rosenbrock, 3, Fill(3, -2), Fill(3, 2)) { EvaluationBudget = 500, ComputeHessian = false };
            a.Minimize();
            Assert.AreEqual("x=BFF2B2CE3E33E989,3FF604F7981C19DA,3FFE45990207C2BE|f=40136C78017992C6|it=495|fe=500|st=Success|trace=500:36029C894805F9ED", OptimizerFingerprint.Of(a));
            var b = new DynamicallyDimensionedSearch(OptimizerFingerprint.SixHumpCamel, 2, new[] { 0.5, 0.5 }, new[] { -3d, -2d }, new[] { 3d, 2d }) { EvaluationBudget = 300, PRNGSeed = 7, ComputeHessian = false };
            b.Maximize();
            Assert.AreEqual("x=C0079645933BB60C,BFFFF04F14AD7C18|f=C062902391F8874D|it=299|fe=300|st=Success|trace=300:9656E2143266C89E", OptimizerFingerprint.Of(b));
        }

        /// <summary>
        /// The reflection rule of Step 4 in Figure 1 of Tolson and Shoemaker (2007).
        /// </summary>
        [TestMethod]
        public void Test_Reflect()
        {
            Assert.AreEqual(0.5, DynamicallyDimensionedSearch.Reflect(0.5, 0, 1));
            Assert.AreEqual(0.2, DynamicallyDimensionedSearch.Reflect(-0.2, 0, 1), 1E-15);
            Assert.AreEqual(0.7, DynamicallyDimensionedSearch.Reflect(1.3, 0, 1), 1E-15);
            // A reflection that passes the opposite bound is set to the violated bound.
            Assert.AreEqual(0.0, DynamicallyDimensionedSearch.Reflect(-1.5, 0, 1));
            Assert.AreEqual(1.0, DynamicallyDimensionedSearch.Reflect(2.5, 0, 1));
            Assert.AreEqual(0.0, DynamicallyDimensionedSearch.Reflect(0.0, 0, 1));
            Assert.AreEqual(1.0, DynamicallyDimensionedSearch.Reflect(1.0, 0, 1));
            Assert.AreEqual(-3.0, DynamicallyDimensionedSearch.Reflect(-5.0, -4, -1));
        }

        /// <summary>
        /// The run spends exactly the budget, including max(5, floor(0.005 m)) initial evaluations, and reports success with a Hessian.
        /// </summary>
        [TestMethod]
        public void Test_BudgetIsSpentAndReportedAsSuccess()
        {
            foreach (var (m, initial) in new[] { (10, 5), (1000, 5), (2000, 10), (5000, 25) })
            {
                var solver = new DynamicallyDimensionedSearch(TestFunctions.DeJong, 3, Fill(3, -5.12), Fill(3, 5.12)) { EvaluationBudget = m };
                solver.Minimize();
                Assert.AreEqual(OptimizationStatus.Success, solver.Status);
                Assert.AreEqual(m, solver.FunctionEvaluations);
                Assert.AreEqual(m - initial, solver.Iterations);
                Assert.HasCount(m, solver.ParameterSetTrace);
                Assert.IsNotNull(solver.Hessian);
            }
        }

        /// <summary>
        /// The base caps stop the run early with their own status.
        /// </summary>
        [TestMethod]
        public void Test_HardCapsStopEarly()
        {
            var a = new DynamicallyDimensionedSearch(TestFunctions.DeJong, 3, Fill(3, -5.12), Fill(3, 5.12)) { EvaluationBudget = 1000, MaxFunctionEvaluations = 400, ReportFailure = false };
            a.Minimize();
            Assert.AreEqual(OptimizationStatus.MaximumFunctionEvaluationsReached, a.Status);
            Assert.AreEqual(400, a.FunctionEvaluations);
            Assert.IsNull(a.Hessian);

            var b = new DynamicallyDimensionedSearch(TestFunctions.DeJong, 3, Fill(3, -5.12), Fill(3, 5.12)) { EvaluationBudget = 1000, MaxIterations = 100, ReportFailure = false };
            b.Minimize();
            Assert.AreEqual(OptimizationStatus.MaximumIterationsReached, b.Status);
            Assert.AreEqual(100, b.Iterations);
            Assert.AreEqual(105, b.FunctionEvaluations);
        }

        /// <summary>
        /// The same seed reproduces the run and a different seed changes it.
        /// </summary>
        [TestMethod]
        public void Test_Determinism()
        {
            string Run(int seed)
            {
                var s = new DynamicallyDimensionedSearch(TestFunctions.Rastrigin, 4, Fill(4, -5.12), Fill(4, 5.12)) { EvaluationBudget = 400, PRNGSeed = seed, ComputeHessian = false };
                s.Minimize();
                return OptimizerFingerprint.Of(s);
            }
            Assert.AreEqual(Run(3), Run(3));
            Assert.AreNotEqual(Run(3), Run(4));
        }

        /// <summary>
        /// Every evaluated point lies within the bounds, including with very wide perturbations.
        /// </summary>
        [TestMethod]
        public void Test_BoundsRespected()
        {
            var lower = new[] { -1d, 0d, 10d };
            var upper = new[] { 1d, 0.01d, 20d };
            int outside = 0;
            double F(double[] x)
            {
                for (int j = 0; j < x.Length; j++)
                    if (x[j] < lower[j] || x[j] > upper[j]) outside++;
                return Corner(x);
            }
            var solver = new DynamicallyDimensionedSearch(F, 3, lower, upper) { EvaluationBudget = 2000, PerturbationSize = 1.0, ComputeHessian = false };
            solver.Minimize();
            Assert.AreEqual(0, outside);
            Assert.AreEqual(2000, solver.FunctionEvaluations);
        }

        /// <summary>
        /// The six-hump camel global minimum is found from every fixed seed.
        /// </summary>
        [TestMethod]
        public void Test_SixHumpCamel()
        {
            for (int seed = 1; seed <= 10; seed++)
            {
                var solver = new DynamicallyDimensionedSearch(OptimizerFingerprint.SixHumpCamel, 2, new[] { -3d, -2d }, new[] { 3d, 2d }) { EvaluationBudget = 1000, PRNGSeed = seed };
                solver.Minimize();
                Assert.AreEqual(-1.031628453489877, solver.BestParameterSet.Fitness, 1E-2);
                var x = solver.BestParameterSet.Values;
                Assert.AreEqual(0.7126, Math.Abs(x[1]), 5E-2);
                Assert.AreEqual(0.0898, Math.Abs(x[0]), 5E-2);
                Assert.IsLessThan(0d, x[0] * x[1]);
            }
        }

        /// <summary>
        /// The 5-D Rastrigin global minimum is reached from fixed seeds within 5,000 evaluations.
        /// </summary>
        [TestMethod]
        public void Test_Rastrigin()
        {
            int success = 0;
            for (int seed = 1; seed <= 10; seed++)
            {
                var solver = new DynamicallyDimensionedSearch(TestFunctions.Rastrigin, 5, Fill(5, -5.12), Fill(5, 5.12)) { EvaluationBudget = 5000, PRNGSeed = seed, ComputeHessian = false };
                solver.Minimize();
                if (solver.BestParameterSet.Fitness < 0.1) success++;
            }
            Assert.IsGreaterThanOrEqualTo(9, success);
        }

        /// <summary>
        /// The 5-D Griewank global minimum is approached from fixed seeds within 5,000 evaluations.
        /// </summary>
        [TestMethod]
        public void Test_Griewank()
        {
            int success = 0;
            for (int seed = 1; seed <= 10; seed++)
            {
                var solver = new DynamicallyDimensionedSearch(Griewank, 5, Fill(5, -600), Fill(5, 600)) { EvaluationBudget = 5000, PRNGSeed = seed, ComputeHessian = false };
                solver.Minimize();
                Assert.IsLessThan(0.25, solver.BestParameterSet.Fitness);
                if (solver.BestParameterSet.Fitness < 0.1) success++;
            }
            Assert.IsGreaterThanOrEqualTo(6, success);
        }

        /// <summary>
        /// DDS reaches the curved 2-D Rosenbrock valley near (1, 1) from fixed seeds but, as the paper notes, it
        /// is not designed to converge precisely, so the tolerance is loose.
        /// </summary>
        [TestMethod]
        public void Test_Rosenbrock()
        {
            int close = 0;
            for (int seed = 1; seed <= 10; seed++)
            {
                var solver = new DynamicallyDimensionedSearch(TestFunctions.Rosenbrock, 2, Fill(2, -2), Fill(2, 2)) { EvaluationBudget = 3000, PRNGSeed = seed, ComputeHessian = false };
                solver.Minimize();
                Assert.IsLessThan(0.3, solver.BestParameterSet.Fitness);
                var x = solver.BestParameterSet.Values;
                // On the valley floor x2 is close to x1^2.
                Assert.AreEqual(x[0] * x[0], x[1], 5E-2);
                if (solver.BestParameterSet.Fitness < 0.05) close++;
            }
            Assert.IsGreaterThanOrEqualTo(5, close);
        }

        /// <summary>
        /// Tolson and Shoemaker (2007, paragraph 42) report that after 2,000 evaluations all 100 DDS trials on their
        /// 10-D Rastrigin variant were within 0.08 of the minimum -10. The same holds for most fixed seeds here.
        /// </summary>
        [TestMethod]
        public void Test_PaperRastrigin10D()
        {
            int close = 0;
            for (int seed = 1; seed <= 30; seed++)
            {
                var solver = new DynamicallyDimensionedSearch(PaperRastrigin, 10, Fill(10, -2), Fill(10, 2)) { EvaluationBudget = 2000, PRNGSeed = seed, ComputeHessian = false, RecordTraces = false };
                solver.Minimize();
                double gap = solver.BestParameterSet.Fitness + 10;
                Assert.IsLessThan(0.2, gap, $"Seed {seed}");
                if (gap <= 0.08) close++;
            }
            Assert.IsGreaterThanOrEqualTo(27, close);
        }

        /// <summary>
        /// Maximize negates the objective and finds the maximum.
        /// </summary>
        [TestMethod]
        public void Test_Maximize()
        {
            var solver = new DynamicallyDimensionedSearch(x => -TestFunctions.DeJong(x), 2, Fill(2, -5), Fill(2, 5)) { EvaluationBudget = 2000 };
            solver.Maximize();
            Assert.AreEqual(OptimizationStatus.Success, solver.Status);
            Assert.AreEqual(0.0, -solver.BestParameterSet.Fitness, 1E-4);
        }

        /// <summary>
        /// The perturbation size must lie in (0, 1].
        /// </summary>
        [TestMethod]
        public void Test_PerturbationSizeValidation()
        {
            foreach (double r in new[] { 0d, -0.1, 1.0000001, double.NaN })
            {
                var solver = new DynamicallyDimensionedSearch(TestFunctions.DeJong, 2, Fill(2, -5), Fill(2, 5)) { PerturbationSize = r };
                Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => solver.Minimize());
                Assert.AreEqual(OptimizationStatus.Failure, solver.Status);
            }
            var ok = new DynamicallyDimensionedSearch(TestFunctions.DeJong, 2, Fill(2, -5), Fill(2, 5)) { PerturbationSize = 1.0, EvaluationBudget = 50 };
            ok.Minimize();
            Assert.AreEqual(OptimizationStatus.Success, ok.Status);
        }

        /// <summary>
        /// Invalid bounds, initial values, and budgets are rejected.
        /// </summary>
        [TestMethod]
        public void Test_InvalidInputs()
