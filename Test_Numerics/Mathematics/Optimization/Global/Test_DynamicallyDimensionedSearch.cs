            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => new DynamicallyDimensionedSearch(TestFunctions.DeJong, 2, Fill(3, -5), Fill(2, 5)));
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => new DynamicallyDimensionedSearch(TestFunctions.DeJong, 2, Fill(2, 5), Fill(2, 5)));
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => new DynamicallyDimensionedSearch(TestFunctions.DeJong, 2, new[] { 0d }, Fill(2, -5), Fill(2, 5)));
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => new DynamicallyDimensionedSearch(TestFunctions.DeJong, 2, new[] { 0d, 6d }, Fill(2, -5), Fill(2, 5)));
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => new DynamicallyDimensionedSearch(TestFunctions.DeJong, 2, new[] { 0d, double.NaN }, Fill(2, -5), Fill(2, 5)));
