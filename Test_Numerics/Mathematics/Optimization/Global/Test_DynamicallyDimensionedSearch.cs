        /// <summary>
        /// An iteration that does not improve the best solution allocates nothing.
        /// </summary>
        /// <remarks>
        /// The test runs alone and takes the smallest of three measurements after two warm-up runs, so that JIT
        /// tiering on the test thread does not count as allocation. Any allocation per iteration would add at least
        /// 19,000 * 24 bytes to every measurement.
        /// </remarks>
        [TestMethod]
        [DoNotParallelize]
        public void Test_ZeroAllocationPerIteration()
        {
            long Allocated(int m)
            {
                double calls = 0;
                // Strictly increasing, so only the first evaluation is ever the best.
                var solver = new DynamicallyDimensionedSearch(x => calls++, 10, Fill(10, -1), Fill(10, 1)) { EvaluationBudget = m, RecordTraces = false, ComputeHessian = false };
                long before = GC.GetAllocatedBytesForCurrentThread();
                solver.Minimize();
                return GC.GetAllocatedBytesForCurrentThread() - before;
            }
            Allocated(1000);
            Allocated(20000);
            long extra = long.MaxValue;
            for (int trial = 0; trial < 3; trial++)
            {
                long small = Allocated(1000), large = Allocated(20000);
                extra = Math.Min(extra, large - small);
            }
            Assert.IsLessThan(1024L, extra, "Extra bytes for 19,000 iterations.");
        }
