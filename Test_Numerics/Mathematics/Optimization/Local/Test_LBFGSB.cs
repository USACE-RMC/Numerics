            double[] a = { 3, -2, 1, -4 };
            var solver = SciPySolver(x => Enumerable.Range(0, 4).Sum(i => a[i] * x[i] + 0.05 * x[i] * x[i]),
                new double[4], Enumerable.Repeat(-1d, 4).ToArray(), Enumerable.Repeat(1d, 4).ToArray(),
                x => Enumerable.Range(0, 4).Select(i => a[i] + 0.1 * x[i]).ToArray());
            solver.Minimize();
            Assert.AreEqual(OptimizationStatus.Success, solver.Status);
            Assert.AreEqual(1, solver.Iterations);
            Assert.AreEqual(2, solver.FunctionEvaluations);
            CollectionAssert.AreEqual(new[] { -1.0, 1.0, -1.0, 1.0 }, solver.BestParameterSet.Values);
        }

        /// <summary>
        /// One-sided and degenerate bounds on the second Rosenbrock coordinate match SciPy.
        /// </summary>
        /// <param name="lower">The lower bound of the second coordinate.</param>
        /// <param name="upper">The upper bound of the second coordinate.</param>
        /// <param name="iterations">SciPy's iteration count.</param>
        /// <param name="evaluations">SciPy's function evaluation count.</param>
        /// <param name="first">SciPy's first coordinate of the optimum.</param>
        /// <param name="fitness">SciPy's objective at the optimum.</param>
        [TestMethod]
        [DataRow(1.2, double.PositiveInfinity, 14, 18, -1.091062466466572, 4.613408209925441)]
        [DataRow(double.NegativeInfinity, 0.8, 33, 44, 0.8947558926512551, 0.17942774085030944)]
        [DataRow(0.5, 0.5, 12, 13, -0.6984564344300603, 3.7064681305022917)]
        public void Test_SciPyOneSidedAndFixedBounds(double lower, double upper, int iterations, int evaluations, double first, double fitness)
        {
            var lo = new[] { double.NegativeInfinity, lower, double.NegativeInfinity, double.NegativeInfinity };
            var hi = new[] { double.PositiveInfinity, upper, double.PositiveInfinity, double.PositiveInfinity };
            var solver = SciPySolver(TestFunctions.Rosenbrock, new[] { -1.2, 1d, -1.2, 1d }, lo, hi, RosenbrockGradient);
            solver.Minimize();
            Assert.AreEqual(OptimizationStatus.Success, solver.Status);
            Assert.AreEqual(iterations, solver.Iterations);
            Assert.AreEqual(evaluations, solver.FunctionEvaluations);
            Assert.AreEqual(first, solver.BestParameterSet.Values[0], 1E-10);
            Assert.AreEqual(fitness, solver.BestParameterSet.Fitness, 1E-12);
            Assert.AreEqual(double.IsInfinity(upper) ? lower : upper, solver.BestParameterSet.Values[1]);
        }

        /// <summary>
        /// A start outside the box is projected onto it before the first evaluation.
        /// </summary>
        [TestMethod]
        public void Test_StartOutsideBoxIsProjected()
        {
            var evaluated = new List<double[]>();
            var solver = new LBFGSB(x => { evaluated.Add((double[])x.Clone()); return (x[0] - 0.5) * (x[0] - 0.5) + x[1] * x[1]; }, 2,
                new[] { 5d, -3d }, new[] { 0d, -1d }, new[] { 1d, 1d }, x => new[] { 2 * (x[0] - 0.5), 2 * x[1] }) { ComputeHessian = false };
            solver.Minimize();
            CollectionAssert.AreEqual(new[] { 1d, -1d }, evaluated[0]);
            Assert.AreEqual(OptimizationStatus.Success, solver.Status);
            Assert.AreEqual(0.5, solver.BestParameterSet.Values[0], 1E-8);
            Assert.AreEqual(0d, solver.BestParameterSet.Values[1], 1E-8);
        }

        /// <summary>
        /// A zero projected gradient at the start succeeds without a step, also when the gradient points out of the box.
        /// </summary>
        [TestMethod]
        public void Test_StationaryStartDoesNotSearch()
        {
            var interior = new LBFGSB(x => x[0] * x[0], 1, new[] { 0d }, new[] { -1d }, new[] { 1d }, x => new[] { 2 * x[0] }) { ComputeHessian = false };
            interior.Minimize();
            Assert.AreEqual(OptimizationStatus.Success, interior.Status);
