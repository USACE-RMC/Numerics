            Assert.AreEqual(1, interior.FunctionEvaluations);

            var boundary = new LBFGSB(x => x[0], 1, new[] { 0d }, new[] { 0d }, new[] { 1d }, _ => new[] { 1d }) { ComputeHessian = false };
            boundary.Minimize();
            Assert.AreEqual(OptimizationStatus.Success, boundary.Status);
            Assert.AreEqual(0, boundary.Iterations);
            Assert.AreEqual(0d, boundary.BestParameterSet.Values[0]);
        }

