        /// <summary>
        /// Cancellation stops the run without throwing and keeps the best point found.
        /// </summary>
        [TestMethod]
        public void Test_Cancellation()
        {
            using var source = new CancellationTokenSource();
            int calls = 0;
            var solver = new LBFGSB(x => { if (++calls == 5) source.Cancel(); return TestFunctions.Rosenbrock(x); }, 2,
                new[] { -1.2, 1d }, new[] { -5d, -5d }, new[] { 5d, 5d }, RosenbrockGradient) { CancellationToken = source.Token };
            solver.Minimize();
            Assert.AreEqual(OptimizationStatus.Cancelled, solver.Status);
            Assert.AreEqual(5, solver.FunctionEvaluations);
            Assert.IsNotNull(solver.BestParameterSet.Values);
            Assert.IsNull(solver.Hessian);
        }

        /// <summary>
        /// Progress is reported at the requested evaluation interval and once at the end.
        /// </summary>
        [TestMethod]
        public void Test_Progress()
        {
            var reports = new List<OptimizationProgress>();
            var solver = new LBFGSB(TestFunctions.Rosenbrock, 2, new[] { -1.2, 1d }, new[] { -5d, -5d }, new[] { 5d, 5d }, RosenbrockGradient)
            { ComputeHessian = false, ProgressInterval = 10, Progress = new SynchronousProgress(reports.Add) };
            solver.Minimize();
            Assert.HasCount(solver.FunctionEvaluations / 10 + 1, reports);
            Assert.AreEqual(solver.FunctionEvaluations, reports[reports.Count - 1].FunctionEvaluations);
        }

        /// <summary>
        /// Invalid arguments are rejected.
        /// </summary>
        [TestMethod]
        public void Test_InvalidArguments()
        {
            Func<double[], double> f = x => x[0] * x[0];
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => new LBFGSB(f, 2, new[] { 0d }, new[] { 0d }, new[] { 1d }));
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => new LBFGSB(f, 1, new[] { 0d }, new[] { 1d }, new[] { 0d }));
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => new LBFGSB(f, 1, new[] { 0d }, new[] { double.NaN }, new[] { 1d }));
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => new LBFGSB(f, 1, new[] { double.NaN }, new[] { 0d }, new[] { 1d }));
            var solver = new LBFGSB(f, 1, new[] { 0d }, new[] { -1d }, new[] { 1d }) { MemorySize = 0 };
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => solver.Minimize());
            solver = new LBFGSB(f, 1, new[] { 0d }, new[] { -1d }, new[] { 1d }) { MaxLineSearchSteps = 0 };
            Assert.ThrowsExactly<ArgumentOutOfRangeException>(() => solver.Minimize());
        }

        /// <summary>Checks a solution component by component.</summary>
        /// <param name="expected">The expected values.</param>
        /// <param name="actual">The actual values.</param>
        /// <param name="tolerance">The absolute tolerance.</param>
        private static void CheckSolution(double[] expected, double[] actual, double tolerance)
        {
            for (int i = 0; i < expected.Length; i++) Assert.AreEqual(expected[i], actual[i], tolerance);
        }

        /// <summary>Creates a solver with the SciPy default tolerances and no Hessian.</summary>
        /// <param name="f">The objective.</param>
        /// <param name="x0">The start.</param>
        /// <param name="lower">The lower bounds.</param>
        /// <param name="upper">The upper bounds.</param>
        /// <param name="gradient">The analytic gradient.</param>
        /// <returns>The configured solver.</returns>
        private static LBFGSB SciPySolver(Func<double[], double> f, double[] x0, double[] lower, double[] upper, Func<double[], double[]> gradient)
        {
            return new LBFGSB(f, x0.Length, x0, lower, upper, gradient)
            {
                AbsoluteTolerance = 1E-5,
                RelativeTolerance = 2.220446049250313E-9,
                ComputeHessian = false
            };
        }

        /// <summary>
        /// The analytic Rosenbrock gradient written with products only.
        /// </summary>
        /// <param name="x">The point.</param>
        /// <returns>The gradient.</returns>
        private static double[] RosenbrockGradient(double[] x)
        {
            var g = new double[x.Length];
            for (int i = 0; i < x.Length - 1; i++)
            {
                double a = x[i + 1] - x[i] * x[i];
                g[i] += -400 * x[i] * a - 2 * (1 - x[i]);
                g[i + 1] += 200 * a;
            }
            return g;
        }

        /// <summary>A progress sink that records reports on the optimizer's thread.</summary>
        private sealed class SynchronousProgress : IProgress<OptimizationProgress>
        {
            private readonly Action<OptimizationProgress> _report;

            /// <summary>Creates the sink.</summary>
            /// <param name="report">The action to run for each report.</param>
            public SynchronousProgress(Action<OptimizationProgress> report) { _report = report; }

            /// <inheritdoc/>
            public void Report(OptimizationProgress value) => _report(value);
        }
    }
