        /// <summary>
        /// The finite-difference gradient and the final Hessian must not evaluate the objective outside the bounds.
        /// </summary>
        [TestMethod]
        public void Test_GradientDoesNotProbeOutsideBounds()
        {
            var lower = new[] { 0d, 0d };
            var upper = new[] { 1d, 1d };
            var violations = new List<string>();
            var solver = new LBFGSB(x =>
            {
                for (int i = 0; i < x.Length; i++)
                    if (x[i] < lower[i] || x[i] > upper[i]) violations.Add("p" + i + "=" + x[i]);
                return Math.Pow(x[0] - 2d, 2d) + Math.Pow(x[1] + 2d, 2d);
            }, 2, new[] { 0.5d, 0.5d }, lower, upper);
            solver.Minimize();
            Assert.IsEmpty(violations, "The objective was evaluated outside the declared bounds: " + string.Join(", ", violations));
            Assert.AreEqual(1d, solver.BestParameterSet.Values[0], 1E-6);
            Assert.AreEqual(0d, solver.BestParameterSet.Values[1], 1E-6);
        }

        /// <summary>
        /// A descending linear objective attains its constrained optimum at the upper bound in one iteration.
        /// </summary>
        [TestMethod]
        public void Test_LinearBoundaryOptimumReportsSuccess()
        {
            var solver = new LBFGSB(x => -x[0], 1, new[] { 0d }, new[] { 0d }, new[] { 1d }, _ => new[] { -1d });
            solver.Minimize();
            Assert.AreEqual(OptimizationStatus.Success, solver.Status);
            Assert.AreEqual(1d, solver.BestParameterSet.Values[0]);
            Assert.AreEqual(1, solver.Iterations);
            Assert.IsNotNull(solver.Hessian);
        }

        /// <summary>
        /// Runs are reproducible bit for bit, with analytic and finite-difference gradients.
        /// </summary>
        /// <remarks>The fingerprint pins the exact search path; see <see cref="OptimizerFingerprint"/>.</remarks>
        [TestMethod]
        public void Test_DefaultRunFingerprint()
        {
            var lower = new[] { -5d, -5d, -5d, -5d };
            var upper = new[] { 5d, 5d, 5d, 5d };
            var analytic = new LBFGSB(OptimizerFingerprint.Rosenbrock, 4, new[] { -1.2, 1d, -1.2, 1d }, lower, upper, RosenbrockGradient) { ComputeHessian = false };
            analytic.Minimize();
            Assert.AreEqual("x=3FEFFFFFB5B8D885,3FEFFFFF744791BD,3FEFFFFEFF926A24,3FEFFFFE13E6761A|f=3D67C28E6B62346F|it=40|fe=50|st=Success|trace=50:531BE0F24D68994F", OptimizerFingerprint.Of(analytic));
            var numeric = new LBFGSB(OptimizerFingerprint.Rosenbrock, 4, new[] { -1.2, 1d, -1.2, 1d }, lower, upper) { ComputeHessian = false };
            numeric.Minimize();
            Assert.AreEqual("x=3FEFFFFD85480D67,3FEFFFFAF9564CFA,3FEFFFF60A3724C7,3FEFFFEB86EE215A|f=3DC44EF165C67BB2|it=38|fe=476|st=Success|trace=476:C50280F71604A5D7", OptimizerFingerprint.Of(numeric));
        }

        /// <summary>
        /// Unbounded Rosenbrock in 2, 5 and 10 dimensions matches SciPy's iterations, evaluations and optimum.
        /// </summary>
        /// <param name="n">The dimension.</param>
        /// <param name="iterations">SciPy's iteration count.</param>
        /// <param name="evaluations">SciPy's function evaluation count.</param>
        /// <param name="last">SciPy's last coordinate of the optimum.</param>
        [TestMethod]
        [DataRow(2, 36, 44, 0.9999980209057526)]
        [DataRow(5, 49, 66, 1.0000034959616948)]
        [DataRow(10, 71, 88, 0.999999553338158)]
        public void Test_SciPyUnboundedRosenbrock(int n, int iterations, int evaluations, double last)
        {
            var x0 = Enumerable.Range(0, n).Select(i => i % 2 == 0 ? -1.2 : 1d).ToArray();
            var solver = SciPySolver(TestFunctions.Rosenbrock, x0, Enumerable.Repeat(double.NegativeInfinity, n).ToArray(),
                Enumerable.Repeat(double.PositiveInfinity, n).ToArray(), RosenbrockGradient);
            solver.Minimize();
            Assert.AreEqual(OptimizationStatus.Success, solver.Status);
            Assert.AreEqual(iterations, solver.Iterations);
            Assert.AreEqual(evaluations, solver.FunctionEvaluations);
            Assert.AreEqual(last, solver.BestParameterSet.Values[n - 1], 1E-8);
        }

        /// <summary>
        /// A weighted quadratic whose minimizer lies outside the box ends on SciPy's active set.
        /// </summary>
        [TestMethod]
        public void Test_SciPyActiveBounds()
        {
            double[] w = { 1, 2, 3, 4, 5, 6 }, c = { -1, 0.5, 2, 0.3, -0.2, 1.5 };
            var solver = SciPySolver(x => Enumerable.Range(0, 6).Sum(i => w[i] * (x[i] - c[i]) * (x[i] - c[i])),
                Enumerable.Repeat(0.5, 6).ToArray(), new double[6], Enumerable.Repeat(1d, 6).ToArray(),
                x => Enumerable.Range(0, 6).Select(i => 2 * w[i] * (x[i] - c[i])).ToArray());
            solver.Minimize();
            Assert.AreEqual(OptimizationStatus.Success, solver.Status);
            Assert.AreEqual(3, solver.Iterations);
            Assert.AreEqual(4, solver.FunctionEvaluations);
            CollectionAssert.AreEqual(new[] { 0.0, 0.5, 1.0, 0.3, 0.0, 1.0 }, solver.BestParameterSet.Values);
            Assert.AreEqual(5.7, solver.BestParameterSet.Fitness, 1E-12);
        }

        /// <summary>
        /// A tilted objective whose solution has every variable at a bound is solved by the Cauchy step alone.
        /// </summary>
        [TestMethod]
        public void Test_SciPyAllBoundSolution()
