        /// <summary>
        /// Asserts that two front lists are identical.
        /// </summary>
        private static void AssertFronts(int[][] expected, List<List<int>> actual)
        {
            Assert.HasCount(expected.Length, actual);
            for (int f = 0; f < expected.Length; f++)
                CollectionAssert.AreEqual(expected[f], actual[f].ToArray(), $"Front {f}");
        }

        /// <summary>
        /// Asserts that two distance vectors agree, with equal infinities.
        /// </summary>
        private static void AssertDistances(double[] expected, double[] actual, double tol)
        {
            Assert.HasCount(expected.Length, actual);
            for (int i = 0; i < expected.Length; i++)
            {
                if (double.IsPositiveInfinity(expected[i])) Assert.IsTrue(double.IsPositiveInfinity(actual[i]), $"Index {i}");
                else Assert.AreEqual(expected[i], actual[i], tol, $"Index {i}");
            }
        }

        /// <summary>
        /// Converts a jagged array to a rectangular array.
        /// </summary>
        private static double[,] ToRect(double[][] a)
        {
            var r = new double[a.Length, a[0].Length];
            for (int i = 0; i < a.Length; i++)
                for (int k = 0; k < a[0].Length; k++) r[i, k] = a[i][k];
            return r;
        }

        /// <summary>
        /// Seeded random points rounded to a grid, so ties and duplicates occur.
        /// </summary>
        private static double[][] RandomPoints(int seed, int n, int m, int decimals)
        {
            var rng = new Random(seed);
            var p = new double[n][];
            for (int i = 0; i < n; i++)
            {
                p[i] = new double[m];
                for (int k = 0; k < m; k++) p[i][k] = Math.Round(rng.NextDouble(), decimals);
            }
            return p;
        }

