            {
                var current = new List<int>();
                for (int i = 0; i < n; i++)
                {
                    if (done[i]) continue;
                    bool dominated = false;
                    for (int j = 0; j < n && !dominated; j++)
                        if (!done[j] && j != i && ParetoFront.Dominates(p[j], p[i])) dominated = true;
                    if (!dominated) current.Add(i);
                }
                foreach (int i in current) { rank[i] = pass; done[i] = true; assigned++; }
            }
            return rank;
        }

        /// <summary>
        /// Hypervolume by inclusion-exclusion over all non-empty subsets of points inside the reference box.
        /// </summary>
        private static double InclusionExclusion(double[][] p, double[] r)
        {
            var inside = p.Where(q => q.Zip(r, (a, b) => a < b).All(x => x)).ToArray();
            int n = inside.Length, m = r.Length;
            double sum = 0;
            for (int mask = 1; mask < (1 << n); mask++)
            {
                double vol = 1;
                int bits = 0;
                for (int k = 0; k < m; k++)
                {
                    double mx = double.NegativeInfinity;
                    for (int i = 0; i < n; i++) if ((mask & (1 << i)) != 0) mx = Math.Max(mx, inside[i][k]);
                    vol *= r[k] - mx;
                }
                for (int i = 0; i < n; i++) if ((mask & (1 << i)) != 0) bits++;
                sum += (bits % 2 == 1 ? 1 : -1) * vol;
            }
            return sum;
        }

